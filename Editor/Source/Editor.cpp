    void Editor::SetCurrentProject(const Project& project, const Path& projectFile)
    {
        mCurrentProject = project;
        mProjectFilePath = projectFile;
        Core::GetPhysics()->ApplySettings(mCurrentProject.Physics);
        mSettingsStore.Load(Filesystem::GetParentPath(projectFile), mSettings);

        Core::SetFrameCap(mSettings.FrameCap);
        mPanelManager.GetPanel<ContentBrowserPanel>()->OnProjectSettingsLoaded();
        mViewports.Restore(mSettings.Viewports);
        mGameResolution = { 0.0f, 0.0f }; // Re-applied to the scene's cameras once the viewports have a size
    }

    void Editor::LoadStartupScene()
    {
        AssetID sceneID = mCurrentProject.StartScene;
        if(mSettings.LastScene && mAssetManager->IsRegistered(mSettings.LastScene))
        {
            const AssetMetadata& metadata = mAssetManager->GetMetadata(mSettings.LastScene);
            if(metadata.Type == AssetType::SCENE && !HasFlag(metadata.Flags, AssetFlags::MISSING))
                sceneID = mSettings.LastScene;
        }

        Ref<Scene> scene = mAssetManager->Load<Scene>(sceneID);
        if(!scene && sceneID != mCurrentProject.StartScene)
            scene = mAssetManager->Load<Scene>(mCurrentProject.StartScene); // The last scene could not be loaded, fall back

        SG_ASSERT(scene, "Failed to load the start scene!");
        LoadScene(std::move(scene));
    }

    void Editor::CloseProject()
    {
        if(IsPlaying())
            OnRuntimeEnd();

        ConfirmDiscardChanges("Leave the project", [this]() {
            SaveSettings();
            mSettingsStore.Reset();
            mProjectFilePath.clear();
            mCurrentProject = {}; // Back to the Project Browser
            mViewports.Clear();   // Their render targets aren't needed in the browser, the next project restores its own
            mProjectBrowser.Refresh();
        });
    }

    void Editor::NewScene()
    {
        if(IsPlaying())
            return;

        ConfirmDiscardChanges("Create a new scene", [this]() {
            const char* extension = GetExtensionFromAssetType(AssetType::SCENE);
            Filesystem::CreateOrEnsureDirectories(Path(mAssetManager->GetAssetsDirectory()) / "Scenes");

            String relativePath = std::format("Scenes/NewScene{}", extension);
            for(int i = 1; Filesystem::Exists(Path(mAssetManager->GetAssetsDirectory()) / relativePath); i++)
                relativePath = std::format("Scenes/NewScene ({}){}", i, extension);

            Ref<Scene> scene = mAssetManager->Create<Scene>(relativePath, Filesystem::GetFilenameWithoutExt(relativePath), Core::GetSceneContext());
            if(!scene)
                return;

            LoadScene(std::move(scene));
            RefreshCameraViewports();
            mPanelManager.GetPanel<ContentBrowserPanel>()->RequestRefresh();
        });
    }

    void Editor::OpenScene(AssetID sceneID)
    {
        if(IsPlaying() || !sceneID || sceneID == mActiveScene->GetID())
            return;

        ConfirmDiscardChanges("Open another scene", [this, sceneID]() {
            Ref<Scene> scene = mAssetManager->Load<Scene>(sceneID);
            if(!scene)
            {
                Log<Severity::Error>("[Editor] Could not open the scene {}", sceneID.Get());
                return;
            }

            LoadScene(std::move(scene));
            RefreshCameraViewports();
        });
    }

    void Editor::SaveSceneAs(const String& relativePath)
    {
        if(IsPlaying())
            return;

        String path = Path(relativePath).generic_string();
        const char* extension = GetExtensionFromAssetType(AssetType::SCENE);
        if(Path(path).extension() != extension)
            path += extension;

        if(mAssetManager->GetIDFromPath(path).IsValid() || Filesystem::Exists(Path(mAssetManager->GetAssetsDirectory()) / path))
        {
            Log<Severity::Warn>("[Editor] Save Scene As: '{}' already exists, pick another name", path);
            return;
        }

        Filesystem::CreateOrEnsureDirectories((Path(mAssetManager->GetAssetsDirectory()) / path).parent_path());
        Ref<Scene> newScene = mAssetManager->Create<Scene>(path, Filesystem::GetFilenameWithoutExt(path), Core::GetSceneContext());
        if(!newScene)
            return;

        mHistory.FlushTracked();
        mActiveScene->CopyTo(newScene.Raw());
        mAssetManager->Save(newScene->GetID());

        // The original file keeps its last saved state, LoadScene() drops its unsaved in-memory edits
        LoadScene(std::move(newScene));

        RefreshCameraViewports();
        mPanelManager.GetPanel<ContentBrowserPanel>()->RequestRefresh();
        Log<Severity::Info>("[Editor] Saved scene as: {}", path);
    }

    void Editor::SaveProject()
    {
        if(!mProjectFilePath.empty())
            mCurrentProject.Save(mProjectFilePath);
    }

    void Editor::SetStartScene(AssetID sceneID)
    {
        if(!sceneID || mProjectFilePath.empty())
            return;

        mCurrentProject.StartScene = sceneID;
        mCurrentProject.Save(mProjectFilePath);
        Log<Severity::Info>("[Editor] Start scene set to: {}", mAssetManager->GetMetadata(sceneID).RelativePath);
    }

    void Editor::FocusEntity(Entity entity)
    {
        // The Scene view the user worked in last, like Unity's F
        SceneViewport* sceneView = mViewports.GetActiveSceneView();
        if(sceneView && entity && entity.HasComponent<TransformComponent>())
            sceneView->GetCamera().Focus(entity.GetComponent<TransformComponent>().GetTransform()[3]);
    }

    void Editor::SaveSettings()
    {
        mViewports.Capture(mSettings.Viewports);
        mSettingsStore.Save(mSettings);
    }

