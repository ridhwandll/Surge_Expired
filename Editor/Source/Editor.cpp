    void Editor::RequestUndo()
    {
        QueueHistoryStep([](EditorHistory& history, UUID& selection) -> bool { return history.Undo(selection); });
    }

    void Editor::RequestRedo()
    {
        QueueHistoryStep([](EditorHistory& history, UUID& selection) -> bool { return history.Redo(selection); });
    }

    void Editor::RequestHistoryJump(size_t position)
    {
        QueueHistoryStep([position](EditorHistory& history, UUID& selection) -> bool { return history.JumpTo(position, selection); });
    }

    void Editor::QueueHistoryStep(std::function<bool(EditorHistory&, UUID&)> step)
    {
        if(IsPlaying())
            return;

        Core::AddFrameEndCallback([this, step = std::move(step)]() {
            UUID selection = UUID::INVALID;
            if(IsPlaying() || !step(mHistory, selection))
                return;

            SelectEntityByUUID(selection);
            RefreshCameraViewports();
        });
    }

    void Editor::RefreshCameraViewports()
    {
        // RuntimeCamera's viewport size is not serialized, cameras recreated from a snapshot need it again
        mActiveScene->OnResize(mGameResolution.x, mGameResolution.y);
    }

    void Editor::ConfirmDiscardChanges(const char* action, std::function<void()> onConfirm)
    {
        if(!mCurrentProject.IsValid() || !mHistory.IsDirty())
        {
            onConfirm();
            return;
        }

        // History is dirty, show a confirmation dialog before discarding changes
        const String message = std::format("The scene has unsaved changes, they will be lost.\n{} without saving?", action);
        ImGuiAux::ShowConfirmationBox("Unsaved Changes", message, std::move(onConfirm));
    }

    void Editor::HandleShortcuts()
    {
        const ImGuiIO& io = ImGui::GetIO();
        const bool ctrl = io.KeyCtrl;
        const bool shift = io.KeyShift;

        // RMB + WASDQE (+Ctrl/Shift) flies the camera, none of these may fire then
        if(ImGui::IsMouseDown(ImGuiMouseButton_Right))
            return;

        // Before the text input check: Ctrl+S right after typing a value must still save
        if(ctrl && !shift && ImGui::IsKeyPressed(ImGuiKey_S, false))
            SaveScene();
        // Also while typing: it closes the drawer whose search box has the focus (InputText ignores Ctrl+Space)
        if(ctrl && !shift && ImGui::IsKeyPressed(ImGuiKey_Space, false))
            mPanelManager.GetPanel<ContentBrowserPanel>()->ToggleDrawer();

        // Text fields keep their own Ctrl+Z/C/V, the UI/Particle/Material Editors run their own history while they are focused
        if(io.WantTextInput || mPanelManager.GetPanel<UIEditorPanel>()->OwnsShortcuts() || mPanelManager.GetPanel<ParticleEditorPanel>()->OwnsShortcuts() || mPanelManager.GetPanel<MaterialEditorPanel>()->OwnsShortcuts())
            return;

        if(ctrl && shift && ImGui::IsKeyPressed(ImGuiKey_S, false) && !IsPlaying())
            mOpenSaveSceneAsPopup = true;
        if(ctrl && !shift && ImGui::IsKeyPressed(ImGuiKey_N, false)) // Ctrl+Shift+N: new folder in the Content Browser
            NewScene();

        if(ctrl && !shift && ImGui::IsKeyPressed(ImGuiKey_Z))
            RequestUndo();
        if(ctrl && (ImGui::IsKeyPressed(ImGuiKey_Y) || (shift && ImGui::IsKeyPressed(ImGuiKey_Z))))
            RequestRedo();

        // Entity shortcuts only while the Hierarchy or the Viewport has the user's attention, other panels reuse these keys (Content Browser: Ctrl+C)
        SceneHierarchyPanel* hierarchy = mPanelManager.GetPanel<SceneHierarchyPanel>();
        if(!hierarchy->IsFocusedOrHovered() && !mViewports.IsSceneViewFocusedOrHovered())
            return;

        Entity selected = GetSelectedEntity();
        if(!ctrl && ImGui::IsKeyPressed(ImGuiKey_F, false) && selected)
            FocusEntity(selected);
        if(ctrl && ImGui::IsKeyPressed(ImGuiKey_C, false) && selected)
            CopyEntity(selected);
        if(ctrl && ImGui::IsKeyPressed(ImGuiKey_V, false))
            PasteEntity();
        if(ctrl && ImGui::IsKeyPressed(ImGuiKey_D, false) && selected)
            DuplicateEntity(selected);
        if(ImGui::IsKeyPressed(ImGuiKey_Delete, false) && selected)
            DeleteEntity(selected);
    }

    void Editor::RenderSaveSceneAsPopup()
    {
        constexpr const char* popupName = "Save Scene As";
        if(mOpenSaveSceneAsPopup)
        {
            mOpenSaveSceneAsPopup = false;
            const AssetID sceneID = mActiveScene->GetID();
            const String current = sceneID && mAssetManager->IsRegistered(sceneID) ? mAssetManager->GetMetadata(sceneID).RelativePath : String("Scenes/NewScene");
            const Path currentPath(current);
            mSaveSceneAsPath = (currentPath.parent_path() / (currentPath.stem().string() + " Copy")).generic_string();
            ImGui::OpenPopup(popupName);
        }

        ImGui::SetNextWindowPos(ImGui::GetMainViewport()->GetCenter(), ImGuiCond_Appearing, ImVec2(0.5f, 0.5f));
        if(!ImGui::BeginPopupModal(popupName, nullptr, ImGuiWindowFlags_AlwaysAutoResize | ImGuiWindowFlags_NoSavedSettings))
            return;

        ImGui::TextUnformatted("Path relative to the Assets folder, the extension is added automatically:");
        ImGui::SetNextItemWidth(420.0f);
        if(ImGui::IsWindowAppearing())
            ImGui::SetKeyboardFocusHere();
        bool confirm = ImGui::InputText("##SceneAsPath", &mSaveSceneAsPath, ImGuiInputTextFlags_EnterReturnsTrue);

        String finalPath = Path(mSaveSceneAsPath).generic_string();
        const char* extension = GetExtensionFromAssetType(AssetType::SCENE);
        if(!finalPath.empty() && Path(finalPath).extension() != extension)
            finalPath += extension;

        const bool emptyName = Path(finalPath).stem().empty();
        const bool exists = !emptyName && (mAssetManager->GetIDFromPath(finalPath).IsValid() || Filesystem::Exists(Path(mAssetManager->GetAssetsDirectory()) / finalPath));
        const bool escapes = !emptyName && (Path(finalPath).is_absolute() || finalPath.find("..") != String::npos);
        const bool valid = !emptyName && !exists && !escapes;
        if(exists)
            ImGui::TextColored(ImVec4(1.0f, 0.4f, 0.45f, 1.0f), "A file already exists at %s", finalPath.c_str());
        else if(escapes)
            ImGui::TextColored(ImVec4(1.0f, 0.4f, 0.45f, 1.0f), "The scene must stay inside the Assets folder");
        else
            ImGui::TextDisabled("%s", emptyName ? "Enter a name" : finalPath.c_str());

        ImGui::Spacing();
        if(!valid)
            ImGui::BeginDisabled();
        confirm |= ImGui::Button("Save", ImVec2(120.0f, 0.0f));
        if(!valid)
            ImGui::EndDisabled();

        ImGui::SameLine();
        if(ImGui::Button("Cancel", ImVec2(120.0f, 0.0f)) || ImGui::IsKeyPressed(ImGuiKey_Escape))
            ImGui::CloseCurrentPopup();
        else if(confirm && valid)
        {
            ImGui::CloseCurrentPopup();
            SaveSceneAs(finalPath);
        }

        ImGui::EndPopup();
    }

